-- Без разовых продуктов (решение 0020): все продукты становятся обычными.
--
-- С версии 1.3 приложение не различает виды продуктов: любой закончившийся продукт сам
-- попадает в покупки. Чтобы прежние версии, которые ещё работают с этой базой, вели
-- бывшие разовые продукты так же, им проставляется kind = 'staple'.
--
-- Столбец kind и его ограничение остаются: прежние версии его читают и пишут.
-- Отметки не меняются: закончившийся бывший разовый продукт, которого нет в покупках,
-- в них и не попадает — это то же состояние «закончилось, не в покупках», что после минуса.
-- updated_at не меняется (0009): место продуктов в списке покупок прежнее.

update public.products set kind = 'staple' where kind = 'one_off';
